/* ============================================================
   js/games/colorNum.js — لعبة «لوّن بالأرقام»
   ------------------------------------------------------------
   شبكة فيها أرقام، وتحتها علب ألوان كل واحدة عليها رقم.
   الطفل يختار لون ويلوّن كل الخانات اللي عليها رقمه،
   وفي الآخر بتظهر صورة بسيطة (قلب، نجمة، شجرة…).
   بتدرّب التمييز بين الأرقام في جو هادي من غير أي ضغط.
   ============================================================ */

/* كل نمط ٦×٦ — كل رقم بيمثّل لون، والشكل بيبان لما يتلوّن كله */
const COLOR_PATTERNS = [
  {name:'قلب', rows:[
    '112211','121121','211112','211112','121121','112211'].map(r => r.split('').map(Number))},
  {name:'نجمة', rows:[
    '113311','113311','331133','113311','131131','311113'].map(r => r.split('').map(Number))},
  {name:'شجرة', rows:[
    '112211','121121','211112','112211','113311','113311'].map(r => r.split('').map(Number))},
  {name:'سمكة', rows:[
    '111221','112222','122223','122223','112222','111221'].map(r => r.split('').map(Number))}
];

const COLOR_BOX = {
  1:{c:'#4CC9A7', name:'أخضر'},
  2:{c:'#FF6B6B', name:'أحمر'},
  3:{c:'#FFC43D', name:'أصفر'}
};

Generators.colorNum = function(lv){
  const pat = sample(COLOR_PATTERNS);
  /* الخانات بالترتيب: صف بصف */
  const cells = [];
  pat.rows.forEach(row => row.forEach(n => cells.push({n})));
  /* الألوان المستخدمة في النمط ده بس */
  const used = [...new Set(cells.map(c => c.n))].sort();

  return {
    type:'colorNum', mode:'color', skill:'color:' + pat.name,
    ask:'لوّن بالأرقام وشوف الصورة',
    speak:'اختار لون وبعدين لوّن كل الخانات اللي عليها نفس الرقم',
    hint:'اضغط على اللون الأول، وبعدين على الخانات اللي عليها رقمه 🎨',
    speakHint:'اختار اللون الأول وبعدين الخانات اللي عليها رقمه',
    cols: pat.rows[0].length,
    cells,
    palette: used.map(n => ({n, color:COLOR_BOX[n].c, name:COLOR_BOX[n].name})),
    picName: pat.name,
    okMsg:`🎨 طلعت صورة ${pat.name}!`
  };
};

const RHYTHM_PADS = [
  {k:0, icon:'🥁', name:'الطبلة',   color:'#FF6B6B'},
  {k:1, icon:'👏', name:'التصفيقة', color:'#FFC43D'},
  {k:2, icon:'🔔', name:'الجرس',    color:'#4C9BFF'}
];

Generators.rhythm = function(lv){
  /* الطول بيزيد بهدوء: ٢ ← ٣ ← ٤ ← ٥ */
  const len = Math.min(1 + lv, 5);
  /* في المستويات الأولى طبلتين بس — أسهل في التمييز */
  const pads = lv <= 1 ? RHYTHM_PADS.slice(0, 2) : RHYTHM_PADS;
  const seq = Array.from({length:len}, () => sample(pads).k);

  return {
    type:'rhythm', mode:'rhythm', skill:'rhythm:' + len,
    ask:'اسمع الإيقاع وكرّره',
    speak:'اسمع الإيقاع كويس وبعدين كرّره',
    hint:'اضغط ▶️ عشان تسمع الإيقاع تاني',
    speakHint:'اضغط زرار التشغيل عشان تسمع تاني',
    pads, seq, len,
    okMsg:'🥁 إيقاع مظبوط!'
  };
};
